export async function legalRoutes(app: FastifyInstance) {
  const headers = {
    'content-type': 'text/html; charset=utf-8',
    'cache-control': 'public, max-age=300',
    // сторінки статичні: ні скриптів, ні зовнішніх ресурсів, ні вбудовування в чужі рамки
    'content-security-policy': "default-src 'none'; style-src 'unsafe-inline'; frame-ancestors 'none'; base-uri 'none'",
    'x-content-type-options': 'nosniff',
  };
  app.get('/privacy', async (_req, reply) => reply.headers(headers).send(privacyHtml()));
  app.get('/delete-account', async (_req, reply) => reply.headers(headers).send(deleteHtml()));
}
