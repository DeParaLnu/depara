import type { FastifyInstance } from 'fastify';
import { config } from '../config';

// Публічні сторінки для магазинів застосунків і користувачів: політика конфіденційності й порядок видалення акаунта.
// Текст описує лише те, що застосунок справді робить (див. код). Перед публікацією в магазинах його має переглянути
// відповідальна особа (юрист університету чи команди): це чернетка по суті, а не юридична консультація.

const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');

const REVISION = '3 листопада 2026 року';

function contact(): string {
  const email = config.privacyContactEmail;
  return email ? `<a href="mailto:${esc(email)}">${esc(email)}</a>` : 'адміністраторів застосунку';
}

